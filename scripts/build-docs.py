"""Build the docs pages (docs/*.html) from the fragments in site/docs-src/.

Run from the repo root:  python3 scripts/build-docs.py
"""
import html
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "site" / "docs-src"
OUT = ROOT / "docs"

PAGES = [
    ("index.html", "Overview", "Orbit documentation: concepts and the system at a glance."),
    ("guide.html", "Using Orbit", "How to use Orbit: bots, chat, screens, groups, calendar, voice and apps."),
    ("setup.html", "Setup", "Install and run Orbit on macOS, Linux, Windows, Docker, desktop and mobile."),
    ("api.html", "API reference", "Orbit's HTTP API, SSE events, WebSockets, MCP tools and core types."),
    ("source.html", "Source code", "A map of Orbit's source: apps, packages, domains, state machines and components."),
]

GITHUB_SVG = '<svg viewBox="0 0 16 16" width="16" height="16" aria-hidden="true"><path fill="currentColor" d="M8 0C3.58 0 0 3.58 0 8c0 3.54 2.29 6.53 5.47 7.59.4.07.55-.17.55-.38 0-.19-.01-.82-.01-1.49-2.01.37-2.53-.49-2.69-.94-.09-.23-.48-.94-.82-1.13-.28-.15-.68-.52-.01-.53.63-.01 1.08.58 1.23.82.72 1.21 1.87.87 2.33.66.07-.52.28-.87.51-1.07-1.78-.2-3.64-.89-3.64-3.95 0-.87.31-1.59.82-2.15-.08-.2-.36-1.02.08-2.12 0 0 .67-.21 2.2.82.64-.18 1.32-.27 2-.27.68 0 1.36.09 2 .27 1.53-1.04 2.2-.82 2.2-.82.44 1.1.16 1.92.08 2.12.51.56.82 1.27.82 2.15 0 3.07-1.87 3.75-3.65 3.95.29.25.54.73.54 1.48 0 1.07-.01 1.93-.01 2.2 0 .21.15.46.55.38A8.013 8.013 0 0016 8c0-4.42-3.58-8-8-8z"/></svg>'


def endpoints(match: re.Match) -> str:
    rows = []
    for line in match.group(1).strip().splitlines():
        method, path, desc = line.split("|", 2)
        m = method.strip().upper()
        rows.append(
            f'<tr><td><span class="m m-{m.lower()}">{m}</span></td>'
            f"<td><code>{html.escape(path.strip())}</code></td><td>{desc.strip()}</td></tr>"
        )
    return (
        '<div class="table-wrap"><table><thead><tr><th>Method</th><th>Path</th><th>Description</th></tr></thead><tbody>'
        + "".join(rows)
        + "</tbody></table></div>"
    )


def build(i: int) -> str:
    fname, title, desc = PAGES[i]
    body = (SRC / fname).read_text()
    body = re.sub(r"<!--endpoints\n(.*?)-->", endpoints, body, flags=re.S)
    toc = re.findall(r'<h2 id="([^"]+)">(.*?)</h2>', body)
    current = ' aria-current="page"'
    nav = "".join(
        f'<li><a href="{f}"{current if f == fname else ""}>{t}</a></li>' for f, t, _ in PAGES
    )
    toc_html = "".join(f'<li><a href="#{a}">{re.sub("<[^>]+>", "", t)}</a></li>' for a, t in toc)
    prev_link = (
        f'<a class="prev" href="{PAGES[i-1][0]}"><small>Previous</small>{PAGES[i-1][1]}</a>' if i > 0 else ""
    )
    next_link = (
        f'<a class="next" href="{PAGES[i+1][0]}"><small>Next</small>{PAGES[i+1][1]}</a>' if i + 1 < len(PAGES) else ""
    )
    page_title = "Orbit docs" if fname == "index.html" else f"{title} · Orbit docs"
    return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{page_title}</title>
  <meta name="description" content="{html.escape(desc)}">
  <meta name="theme-color" content="#161616">
  <link rel="icon" type="image/svg+xml" href="../site/media/bot-orange.svg">
  <meta property="og:title" content="{page_title}">
  <meta property="og:description" content="{html.escape(desc)}">
  <meta property="og:image" content="https://raybello.github.io/orbit/site/media/brag.jpg">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=JetBrains+Mono:wght@400;500&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="../site/styles.css">
  <link rel="stylesheet" href="../site/docs.css">
</head>
<body>
  <!-- Generated by scripts/build-docs.py from site/docs-src/. Edit the source and rebuild. -->
  <header class="nav">
    <div class="wrap nav__inner">
      <a class="brand" href="../" aria-label="Orbit home">
        <img src="../site/media/bot-orange.svg" alt="" width="28" height="28">
        <span>Orbit</span>
      </a>
      <nav class="nav__links" aria-label="Site">
        <a href="../#features">Features</a>
        <a href="./" aria-current="page">Docs</a>
        <a href="api.html">API</a>
      </nav>
      <a class="btn btn--ghost btn--sm" href="https://github.com/raybello/orbit">{GITHUB_SVG} GitHub</a>
    </div>
  </header>
  <div class="wrap docs">
    <aside class="docs-nav" aria-label="Documentation">
      <h4>Docs</h4>
      <ul>{nav}</ul>
      <div class="toc-block">
        <h4>On this page</h4>
        <ul class="toc">{toc_html}</ul>
      </div>
    </aside>
    <main class="doc" id="top">
{body}
      <nav class="pager" aria-label="Pages">{prev_link}{next_link}</nav>
    </main>
  </div>
  <footer class="footer">
    <div class="wrap footer__inner">
      <span>Orbit is MIT licensed. Spot a mistake? <a href="https://github.com/raybello/orbit/issues">Open an issue</a>. Source for these pages: <code>site/docs-src/</code>.</span>
    </div>
  </footer>
  <script src="../site/main.js"></script>
</body>
</html>
"""


for i, (fname, *_rest) in enumerate(PAGES):
    (OUT / fname).write_text(build(i))
    print("wrote", OUT / fname)
